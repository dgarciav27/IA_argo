"""
Isolation Forest training for 3 oceans (Atlantic, Indian, Pacific)

-To run after: /.../preprocessing.ipynb

Load the splits generated by argo_preprocess.py for each ocean.
For each ocean:
  - Optimize F1-macro with HalvingRandomSearchCV (CV on train only)
  - Tune the threshold (score percentile) on val
  - Evaluate on test
  - Save everything in its own results folder and its own MLflow experiment

NOTE:
Isolation Forest is an UNSUPERVISED anomaly detector: it is fitted
on X (without using y) and produces a continuous anomaly score (higher =
more anomalous). To enable a seamless comparison with XGBoost/LightGBM
in this pipeline:

  - sklearn.ensemble.IsolationForest is wrapped in a custom class
    (IsolationForestF1) that exposes predict()/score() in the same
    0=Good / 1=Bad format used by the other scripts, allowing us to:
      * use HalvingRandomSearchCV with scoring="f1_macro" (compares
        predict() for each fold against the true labels)
      * perform threshold tuning on val just like with XGBoost/LightGBM,
        but sweeping PERCENTILES of the anomaly score (rather than a fixed
        0.05-0.95 grid, because IsolationForest scores are not bounded
        between 0 and 1 like probabilities)
"""

